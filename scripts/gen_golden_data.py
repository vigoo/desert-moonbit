#!/usr/bin/env python3
"""Regenerate golden_data.mbt from testdata/dataset1.bin.

The golden dataset is produced by the original Scala desert library
(golden-dataset-generator) and shared with desert-rust's golden test.
It is checked in as generated MoonBit source so the test runs on every
target without file I/O. Bytes literals cannot span lines, so the data
is emitted as fixed-size parts joined by the test helper.
"""
import sys

src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
PART = 2048
parts = []
for off in range(0, len(data), PART):
    chunk = data[off : off + PART]
    body = "".join("\\x%02x" % b for b in chunk)
    parts.append(body)
with open(dst, "w") as f:
    f.write("// Generated by scripts/gen_golden_data.py from testdata/dataset1.bin — DO NOT EDIT.\n")
    f.write("// Source: the golden dataset produced by desert-scala, shared with desert-rust.\n")
    f.write("// Use `golden_dataset1()` to obtain the bytes.\n\n")
    f.write("let dataset1_parts : Array[Bytes] = [\n")
    for body in parts:
        f.write('  b"%s",\n' % body)
    f.write("]\n\n")
    f.write("""///|
/// The 242540-byte golden dataset written by desert-scala
/// (`golden/dataset1.bin` of the original library).
pub fn golden_dataset1() -> Bytes {
  let builder = BytesBuilder()
  for part in dataset1_parts {
    builder.add(part)
  }
  builder.to_bytes()
}
""")
print(f"wrote {dst} ({len(data)} bytes in {len(parts)} parts)")
